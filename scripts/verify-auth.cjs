// Isolated service/guard integration suite. No sockets, configured DB, email, or payments.
process.env.DATABASE_URL = 'memory://';
process.env.APP_ENV = 'demo';
process.env.PAYPAL_MODE = 'sandbox';
process.env.RESEND_API_KEY = '';
process.env.PAYPAL_CLIENT_ID = '';
process.env.PAYPAL_CLIENT_SECRET = '';
process.env.GEMINI_API_KEY = '';
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
require('../apps/api/node_modules/reflect-metadata');
const dbm = require('../packages/db/dist/index.js');
const { AuthService } = require('../apps/api/dist/modules/auth/auth.service.js');
const { AuthController } = require('../apps/api/dist/modules/auth/auth.controller.js');
const { SessionMiddleware } = require('../apps/api/dist/common/session.middleware.js');
const { SessionAuthGuard, MerchantRoleGuard, CaseAccessGuard } = require('../apps/api/dist/common/guards.js');
const { AuthRateGuard, DemoOnlyGuard } = require('../apps/api/dist/modules/auth/auth.security.js');
const { CasesService } = require('../apps/api/dist/modules/cases/cases.service.js');
const { CasesController } = require('../apps/api/dist/modules/cases/cases.controller.js');
const { CatalogController } = require('../apps/api/dist/modules/catalog/catalog.controller.js');
const { CatalogService } = require('../apps/api/dist/modules/catalog/catalog.service.js');
const contracts = require('../packages/contracts/dist/index.js');
const context = req => ({ switchToHttp: () => ({ getRequest: () => req }) });

async function main() {
  await dbm.runSeed();
  const db = await dbm.getDb();
  const auth = new AuthService();
  const controller = new AuthController(auth);
  const middleware = new SessionMiddleware();
  const cases = new CasesService();
  const caseController = new CasesController(cases);
  const catalog = new CatalogController(new CatalogService());
  const response = { headers: {}, cookies: {}, setHeader(k,v) { this.headers[k] = v; }, cookie(k,v,o) { this.cookies[k] = { value:v, options:o }; }, clearCookie(k) { delete this.cookies[k]; } };
  const requestFor = async token => { const req = { headers: {}, cookies: { resolvepay_session: token }, params: {} }; await middleware.use(req, {}, () => {}); return req; };
  let checks = 0;
  const check = (condition, message) => { assert.ok(condition, message); checks++; };
  const rejects = async (fn, pattern) => { await assert.rejects(fn, pattern); checks++; };
  const throws = (fn, pattern) => { assert.throws(fn, pattern); checks++; };
  throws(() => new SessionAuthGuard().canActivate(context({})), /required/);
  throws(() => contracts.CustomerAccessRedeemDtoSchema.parse({ token: 'invalid' }));
  const dto = contracts.CustomerAccessRequestDtoSchema.parse({ orderReference: ' ORD-2026-9041 ', email: ' ALEX.CUSTOMER@EXAMPLE.COM ' });
  const requested = await auth.requestCustomerAccess(dto);
  check(requested.devToken, 'Matching normalized order receives a link');
  const customer = await controller.redeemAccess({ token: requested.devToken }, {}, response);
  const cookie = response.cookies.resolvepay_session;
  check(cookie.options.httpOnly && cookie.options.sameSite === 'lax' && cookie.options.path === '/', 'Cookie protection');
  check(!customer.token, 'Secret is not exposed in response body');
  await rejects(() => auth.redeemCustomerAccess({ token: requested.devToken }), /Invalid|expired/);
  const req = await requestFor(cookie.value);
  const session = req.sessionInfo;
  check(session?.actorType === 'CUSTOMER', 'Session middleware validates cookie');
  check(await catalog.getOrder(session.orderId, req), 'Own order readable');
  await rejects(() => catalog.getOrder(randomUUID(), req), /access link/);
  throws(() => new MerchantRoleGuard().canActivate(context(req)), /Merchant/);
  const ownCase = await cases.createCase({ orderId: session.orderId, initialMessage: 'The zipper arrived broken.', channel: 'WEB' }, session);
  const foreignOrder = randomUUID();
  await db.insert(dbm.orders).values({ id: foreignOrder, tenantId: session.tenantId, orderReference: 'OTHER-ORDER', customerId: '20000000-0000-0000-0000-000000000001', customerEmail: session.customerEmail, customerName: 'Same email, different order', status: 'PAID', currency: 'USD', subtotalMinor: '100', taxMinor: '0', shippingMinor: '0', totalMinor: '100' });
  const [foreignCase] = await db.insert(dbm.cases).values({ tenantId: session.tenantId, orderId: foreignOrder, customerId: '20000000-0000-0000-0000-000000000001', issueType: 'damaged', state: 'OPEN' }).returning();
  await rejects(() => cases.createCase({ orderId: foreignOrder, initialMessage: 'Wrong order', channel: 'WEB' }, session), /access link/);
  check((await caseController.listCases(req)).every(c => c.orderId === session.orderId), 'List is order scoped');
  req.params.id = foreignCase.id;
  await rejects(() => new CaseAccessGuard().canActivate(context(req)), /another order/);
  req.params.id = ownCase.id;
  check(await new CaseAccessGuard().canActivate(context(req)), 'Own case permitted');
  await controller.logout(req, response);
  check(!(await requestFor(cookie.value)).sessionInfo, 'Logout revokes cookie server-side');

  const mr = await auth.requestMerchantAccess({ tenantSlug: 'default-merchant', email: 'OWNER@PEAKGEAR.DEMO' });
  const merchant = await auth.redeemMerchantAccess(mr.devToken);
  const merchantReq = await requestFor(merchant.token);
  check(merchantReq.sessionInfo?.role === 'MERCHANT_OWNER', 'Merchant role from active membership');
  check(new MerchantRoleGuard().canActivate(context(merchantReq)), 'Merchant accepted');
  await rejects(() => auth.redeemMerchantAccess(mr.devToken), /expired|used/);
  throws(() => new MerchantRoleGuard().canActivate(context({ sessionInfo: { ...merchant.session, role: undefined } })), /not authorized/);
  const rotated = await controller.loginDev({ persona: 'CUSTOMER' }, merchantReq, response);
  check(!(await requestFor(merchant.token)).sessionInfo, 'Switching identities revokes old session');
  await db.update(dbm.sessions).set({ expiresAt: new Date(0) }).where(dbm.eq(dbm.sessions.id, rotated.session.sessionId));
  check(!(await requestFor(response.cookies.resolvepay_session.value)).sessionInfo, 'Expired session denied');
  const single = await auth.requestCustomerAccess(dto);
  const results = await Promise.allSettled([auth.redeemCustomerAccess({ token: single.devToken }), auth.redeemCustomerAccess({ token: single.devToken })]);
  check(results.filter(r => r.status === 'fulfilled').length === 1, 'Concurrent single use');
  const expired = await auth.requestMerchantAccess({ tenantSlug: 'default-merchant', email: 'owner@peakgear.demo' });
  await db.update(dbm.merchantLoginTokens).set({ expiresAt: new Date(0) });
  await rejects(() => auth.redeemMerchantAccess(expired.devToken), /expired/);
  const unknown = await auth.requestMerchantAccess({ tenantSlug: 'default-merchant', email: 'unknown@example.com' });
  check(!unknown.devToken && unknown.message, 'Unknown account generic response');
  const pending = await auth.requestMerchantAccess({ tenantSlug: 'default-merchant', email: 'owner@peakgear.demo' });
  await db.update(dbm.memberships).set({ status: 'INACTIVE' }).where(dbm.eq(dbm.memberships.userId, merchant.session.actorId));
  await rejects(() => auth.redeemMerchantAccess(pending.devToken), /no longer/);
  check(!(await requestFor(merchant.token)).sessionInfo, 'Revoked membership denied');
  const blocked = await auth.requestCustomerAccess(dto);
  await db.update(dbm.tenants).set({ status: 'INACTIVE' }).where(dbm.eq(dbm.tenants.id, session.tenantId));
  await rejects(() => auth.redeemCustomerAccess({ token: blocked.devToken }), /no longer available/);
  const inactive = await auth.requestCustomerAccess(dto);
  check(!inactive.devToken, 'Inactive store cannot issue customer links');
  await db.update(dbm.tenants).set({ status: 'ACTIVE' }).where(dbm.eq(dbm.tenants.id, session.tenantId));
  process.env.APP_ENV = 'production';
  throws(() => new DemoOnlyGuard().canActivate(), /disabled/);
  await rejects(() => auth.loginDevPersona('OWNER'), /disabled/);
  await rejects(() => auth.requestMerchantAccess({ tenantSlug: 'default-merchant', email: 'owner@peakgear.demo' }), /temporarily unavailable/);
  const rate = new AuthRateGuard();
  for (let i=0; i<20; i++) rate.canActivate(context({ ip: 'test' }));
  throws(() => rate.canActivate(context({ ip: 'test' })), /Too many/);
  console.log(`PASS: ${checks} service/controller/guard checks: link redemption, replay, expiry, ownership, roles, revocation, rotation, demo isolation, rate limit.`);
}
main().then(() => process.exit(0)).catch(error => { console.error(error); process.exit(1); });
